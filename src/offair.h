// ============================================================
//  offair.h —— 「这台现在不播」台账（1.46.6）
//
//  要解决的事：台表里几百个台，很多有播出时间 —— 凌晨停播、白天才开。
//  以前的做法是"转到它 → 连不上 → 沙沙响 30 秒 → 再试 → 再沙沙"，
//  老人不知道该转走还是该等。
//
//  这版的做法（不改台表、不重排顺序）：
//    · 检测：连不上**两回**（第一回照旧补沙沙）、或者解出来的样本连续 8 秒全是 0
//      → 判定「这台现在不播」，记进台账；
//    · 隐藏：旋钮/遥控/App 换台时直接跳过它们，一格一个能听的台；
//    · 复活：台账带倒计时（15 / 30 / 45 / 60 分钟封顶），到点自动回到列表；
//      回来的第一次用 9 秒短超时复查 —— 还在停播就再藏起来，开播了就当没事。
//
//  为什么不按"播出时间表"做：那需要每个台一张表，几百个台没有可靠数据，
//  而且台临时检修、地址换 CDN 都会失效。检测式的好处是**不依赖任何外部数据**，
//  连"这个台今天临时不播"都能覆盖。
// ============================================================
#pragma once
#include <Arduino.h>

void offairBegin();     // setup：读 /offair.bin（要在 storeLoad 之后）
void offairTick();      // loop：合并写盘 + 每 5 分钟刷新一次倒计时

// ---- 查询 ----
bool offairSkip(int idx);      // 这台现在该跳过吗（真机导航都走它）
bool offairProbe(int idx);     // 以前判过、刚到期回来 → 值得用短超时先复查
int  offairHidden();           // 现在被跳过几台（屏上「跳过 N」用）
bool offairEnabled();          // 总开关

// ---- 判定（由 audio.cpp 调）----
bool offairMark(int idx);      // 判「现在不播」：进台账，退避加码。返回 false = 不处理
void offairOk(int idx);        // 出过声：把这台的记录清掉

// ---- 导航 ----
// 按「节目单元」走一格（一部书算一个），跳过台账里的台。
// 全表都被跳过时退回普通一格 —— 宁可走回一个停播台，也不能让旋钮卡死。
int  offairStep(int idx, int dir);
// 开机用：从 idx 起找第一个不在台账里的台（全都被跳过就返回 idx）
int  offairFirstAudible(int idx);

// ---- 管理 ----
void offairClearAll();              // 全部放回
void offairSetEnabled(bool on);     // 关掉 = 一台都不跳（老机器/调试用）
void offairJson(String& o);         // GET /api/offair
