// ============================================================
//  evlog.h —— 1.46.39：板载事件日志（环形缓冲，可远程读）
//
//  为什么加这个：
//    用户报的「断网后再有网，没有回到网络广播」「收频段没声音」这类问题，
//    都发生在**没有网络**的时候 —— 那个时段 HTTP 连不上、USB 也不一定插着，
//    事后什么证据都没留下，只能靠猜（今天已经猜错一次，把用户的自动调台
//    当成了 bug）。
//    现在关键事件都记在这个环形缓冲里：网络恢复后打开 /api/log 就能看到
//    「几点几分 WiFi 掉了 → 几秒后进收音 → 搜台几个 → 什么时候回来的 →
//     有没有退回收音模式 → 音频起播成功没有」。
//
//  容量：64 条 × 96 字节 ≈ 6 KB 静态内存，够装一次完整的断网-恢复过程。
// ============================================================
#pragma once
#include <Arduino.h>

// 记一条。tag 是短标签（"net" / "fm" / "audio" / "key"），msg 是内容。
void evlog(const char* tag, const char* fmt, ...);

// 输出成 JSON：{"n":条数,"list":["12.3 net: ...", ...]}（老的在前）
void evlogJson(String& o);

// 清空（诊断用）
void evlogClear();

// 开机记一条（带上版本号），setup 末尾调一次
void evlogBoot(const char* ver);
