// ============================================================
//  pairpin.h —— 4 位「手机连接码」（1.46.5）
//
//  为什么加它：
//    App 原来只能靠 mDNS 或「扫 254 个地址」找机器。前者很多路由器直接
//    把组播丢了，后者在 /16 网段或 AP 隔离的网里永远扫不到 —— 用户看到
//    的就是「App 连不上收音机」，而机器其实好好的。
//    现在给机器一个**人记得住的编号**：屏幕上/说明书上写着 1234，
//    手机输 1234 就找到它，UDP 广播一问就答，0.2 秒出结果。
//
//  它不是密码：
//    答话里只有名字 / 版本 / IP / 设备码（这些本来就在 /api/info 里公开），
//    不含令牌、不含遥控码。真正管权限的是配对令牌（storeToken）。
// ============================================================
#pragma once
#include <Arduino.h>

void        pinBegin();                 // 开机读 /pin.txt（没有就写 1234）
void        pinLoop();                  // 在 loop 里调：UDP 有人问就答
const char* pinCode();                  // 当前 4 位码
bool        pinSetCode(const char* c);   // 改成 c（必须 4 位数字）
bool        pinMatch(const char* c);     // 对不对
void        pinShow();                   // 在屏上显示一次（60 秒后自动回主界面）
