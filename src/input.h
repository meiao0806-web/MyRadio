// ============================================================
//  input.h —— 旋钮 + 红外遥控
//
//  旋钮（全机唯一按键）：
//    旋转          → 上一个 / 下一个台
//    按住旋转      → 音量 ±（遥控器丢了也能调）
//    短按          → 播放 / 暂停
//    双击          → 静音开 / 关
//    长按          → 重连当前台（老人最常用的一招）
//
//  红外遥控（可选硬件，VS1838B 一个脚）：
//    CH+ / CH-     → 下一台 / 上一台
//    VOL+ / VOL-   → 音量
//    PLAY          → 播放暂停
//    首次使用按住旋钮上电 → 进入「学习模式」，按 5 个键自动记下，不用改代码
// ============================================================
#pragma once
#include "state.h"

void inputBegin();
void inputLoop();
bool inputLearnActive();      // 是否在遥控器学习模式（屏上会提示）
const char* inputLearnHint(); // 学习进度提示
const char* inputEncDiag();   // 1.45.5：编码器每格几个边沿（/api/enc）
