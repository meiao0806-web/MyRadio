// 1.46.65 ---------------- FM 弱信号听感 ----------------
//   1.46.62 用 /api/fmprobe 在真机上量到的原始值（dBuV）：
//     98.0MHz  rssi=17~27  snr=1~5      86.0MHz  rssi=27~31  snr=7~8
//   SI473x 的 RSSI 正常室内应该有 40~60。这里长期在 20 上下，说明**天线基本是空的**
//   （这类模块靠耳机线当天线，而耳机口现在被 3.5mm 线接到功放 LINE IN 了）。
//
//   弱信号下最伤听感的不是"信号弱"，是**立体声解码**：SNR 只有 3dB 时，
//   L/R 分离出来的几乎全是噪声，芯片还会因为 blend 把两路能量对消一部分 ——
//   用户听到的就是"沙沙的、还很小声"。
//
//   AN332 的属性：FM_BLEND_STEREO_THRESHOLD（dBuV）
//     · 设 0   = 永远立体声（默认，弱台等于自找噪声）
//     · 设 127 = 永远单声道
//   设 40 表示「RSSI 低于 40 就退成单声道」：本机 20~31 的台全部走单声道，
//   可听度和响度都会明显好于立体声；真有强台（RSSI > 40）时仍然是立体声。
