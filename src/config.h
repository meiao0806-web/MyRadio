// ---- 1.46.20：旋钮「一格」不再数边沿，改认 detent（机械停位）----
//   历史包袱（1.45.5 ~ 1.46.19）全是「累计原始边沿 ÷ N」。这条路走不通，原因很实在：
//   这颗 EC11 每格的边沿数**不是常数** —— 真机 /api/enc 抓到 1 / 4 / 17 / 49 都出现过
//   （轻拨 1~2 个、正常 4 个、连拨几十个）。任何固定除数都会把边沿少的一格算成半格、
//   把边沿多的一格算成三四格：
//     · 除小了   → 「快转一格却调了 3 台」（1.46.20 用户报的）
//     · 余数凑格 → 「轻轻动一点点台变了，松手又变回来」
//   现在只认机械事实：每一格都**停在同一个 AB 电平**（detent）上，一格 = 走完一个
//   正交循环、中途必然经过**对侧电平**。判据实现在 input.cpp 的 encIsr 里。
//
//   ENC_DET_LEARN_MS：AB 静止这么久，就把当前电平认成 detent。
//   开机读一次 + 运行中自愈，所以不必事先知道这块板子的 detent 是 11 还是 00。
#define ENC_DET_LEARN_MS 1200

