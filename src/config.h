#define AGC_TARGET_RMS_BOOK  7000
#define AGC_MAX_GAIN_BOOK    12.0f
#define NOISE_SIL_BLOCKS    40      // 连续 40 块（≈1 秒）静音 → 判定没信号，开始补噪声
