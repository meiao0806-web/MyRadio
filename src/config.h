//   （1.46.4 实测 #01839d 的绿被抬了 +109），一抬就从「砖红」变「橙黄」。
//   换成 #B20A0A 后绿只有 10，抬到顶也还是红 —— 用户要的就是这个红。
#define C_ERR       0xB041   // #b20a0a 断网红 / FM 红点（与指针同色）

// ---- 调谐盘（1.4.2 起照参考图配色，见 tools/ 里的刻度盘样张）----
#define C_DIAL_BG   0x0A6B   // #084d5a 盘底：深青绿
#define C_DIAL_FG   0xEFBE   // #eef4f4 频率数字（近白）
#define C_DIAL_MK   0xCF5D   // #c8e8e8 刻度线（浅青白，比数字暗一档）
#define C_DIAL_PTR  0xB041   // #b20a0a 指针：红（1.46.20 由橙棕改，原因见 C_ERR）
#define C_WARN      0xAB40   // 警告橙（同高亮）

// ---- 1.38.0：原厂配色（照 ALL_IN_ONE_T-Display_S3.ino 的 drawSprite）----
//   原厂就四个色：黑底、白字/白框、红（指针 + 中心刻度 + 强信号）、
//   灰 0xC638（刻度）。这里原样搬过来 —— 这块屏在户外强光下，
//   黑底白字的对比度是最高的，花花绿绿的配色反而看不清。
#define C_WHITE     0xFFFF   // TFT_WHITE
#define C_RED       0xF800   // TFT_RED（指针、中心刻度）
#define C_TICK      0xC638   // 刻度灰（原厂 lineColor 的同款值）
#define C_SIGLOW    0x3526   // 弱信号柱（原厂的暗青绿）

// ---- 1.40.0：电量三档配色（用户指定）----
//   ≥40% 蓝 / <40% 黄 / <10% 红
//   为什么不用原来那套青（C_COOL 0x0413）：那个值转成 RGB 是 #00829c，
//   在真机小屏上偏"墨绿",和预览页的蓝对不上，用户一眼就看出来了。
//   下面三个是**饱和度高**的纯色，转成 RGB565 损失小，两边看着才一致。
//     #2E86FF → 0x2C1F（蓝）
//     #FFC400 → 0xFE20（黄）
//     #FF3B30 → 0xF9A6（红）
//  1.40.1：高电量那一档改成 **C_COOL 同值**。
//
//  用户原话：「电量图标的蓝色是指和 wifi 图标一样的颜色」。
//  原来我用的 0x2C1F 是 #2E86FF（偏紫的亮蓝），而界面上其他所有"蓝"都是
//  C_COOL = #00829c 那个青蓝（信号柱、仪表、刻度都用它）。
//  两个蓝并排放在顶栏里，一眼就不像一套东西。
//
//  现在直接写成和 C_COOL 一样的值。注意：**不要改成 `#define C_BATT_HI C_COOL`**，
//  因为预览页生成脚本（gen_webpreview.py）是用正则抠 `0xNNNN` 字面量的，
//  换成宏名它就抠不到了，预览页会缺这一项、颜色掉回黑色 —— 又变成两边不一致。
#define C_BATT_HI   0x0413   // ≥40%：青蓝（与信号柱 C_COOL 同色）
#define C_BATT_MID  0xFE20   // <40%：黄
#define C_BATT_LOW  0xF9A6   // <10%：红（比 C_RED 稍偏橙，小屏上更醒目）

// ---- 1.46.4：真机色补偿（只改"画到屏上"的值，设计色一个字不动）----
//   用户拿取色器在真机上量了这两个图标（预览页是电脑上看到的颜色）：
//     · 青蓝 信号柱 / 电量：设计 #01839d (0x0413) → 真机量到 #64f0fa
//     · 橙   网络广播徽标：设计 #b06b03 (0xAB40) → 真机量到 #fdf100
//
//   **两边相减的差值不能直接减**。target - measured 算出来是
//     (-99,-109,-93) 和 (-77,-134,+3)，照这个减：青蓝变成 #00153f（黑到看不见），
//     徽标变成 #5e0003（黑字对比度 1.9:1，老人根本读不出）。
//   所以按「面板整体提亮 ≈1.8~2.3 倍、橙的绿通道被顶满」做半档反推：
//     C_COOL    #00829c（相对亮度 0.183）→ #00657b（0.105，压掉约 43%）
//     C_BAND_BG #ab6900 → #ab4d00：只压绿通道 105→77，红**不动** ——
//       "看着发黄"就是绿顶到 241 造成的；红保住，黑字对比度 4.75:1 → 3.8:1 仍然够读。
//
//   为什么单起一层 *_PAINT：
//     gen_webpreview.py 是按 `#define C_XXX 0xNNNN` 抠设计色渲染预览页的，
//     预览页是"应该长什么样"的基准，不该被补偿值污染。它的正则是
//     `#define\s+C_([A-Z0-9_]+)\s+(0x....)`，COOL_PAINT / BAND_BG_PAINT
//     不在 _C_KEY 映射表里，会被自动跳过（tools/verify_palette.py 盯着这条）。
//
//   嫌暗/嫌艳只改下面三个数，**不要**去动上面的设计色。
#define C_COOL_PAINT     0x032F   // (0,101,123)：信号柱、状态点、仪表
#define C_BATT_HI_PAINT  0x032F   // 电量 ≥40% 那一档（与信号柱同色）
#define C_BAND_BG_PAINT  0xAA60   // (171,77,0)：网络广播徽标底（黑字不变）
