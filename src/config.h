// ============================================================
//  1.46.0：让 "换台" 听起来像收音机，而不是像换了台设备
// ------------------------------------------------------------
//  ① 自动增益（AGC）—— 治「同一个音量，各台声大声小」
//
//     实测（同一批蜻蜓 64k mp3，同一个音量刻度，只量源头）：
//       成都 FM96.5   -8.2 dBFS   ← 最响
//       成都年代音乐  -11.6
//       成都经济广播  -15.2
//       成都 FM94.6   -20.0 dBFS  ← 最轻
//     最响比最轻高 **12 dB**，也就是手上是 4 倍的音量差。用户的原话是
//     「所有台声音大小不统一，一会大一会小」。
//
//     做法：在解码出 PCM、写 I2S 之前（audio_process_extern 里）乘一个**慢变**增益，
//     把每台的 RMS 拉向 AGC_TARGET_RMS。为什么要慢（AGC_STEP）：
//     快了就成了压缩器，人声一停一响会"抽气"，比原来更难听。
//     为什么要限幅（AGC_MAX/MIN）：只修 12 dB 这个量级的源差异，
//     不试图把一声叹息也放大成广播——那种"背景噪声被抬起来"的效果更糟。
//
//  ② 没信号时的「滋滋」声 —— 治「换到坏台一片死寂，以为机器坏了」
//
//     两种情况都得有声音，但成因完全不同，所以走两条路：
//       · 流是通的、样本全是 0（天津滨海 20003 实测 RMS -95.6 dBFS，
//         就是一个"活着的静音流"，看门狗永远判不出它坏）
//         → 在 PCM 回调里直接填噪声。这一条不需要动网络，真声音一回来
//           噪声立刻消失（下一块就不再是静音块了）。
//       · 连不上 / 秒断（成都故事广播 5022004、成都新闻广播 4897 的
//         蜻蜓台号现在直接 404）
//         → 放本地 /noise.wav 循环，每 NOISE_RETRY_MS 再试一次真流。
//           台名不变、进度不变，用户听到的就是"这个台没信号"。
//
//     ⚠️ 从 1.46.0 起，连不上的台**不再自动跳到下一台**（1.45.x 的行为）。
//        老人看到的是「台自己跑了」，比"沙沙响"更让人困惑。
//        真嫌吵就转一格，旋钮换台逻辑一点没动。
// ============================================================
#define AGC_ON             1        // 0 = 完全关掉自动增益（回到 1.45.x 的响度）
// ---- 1.46.18：音量归一范围放宽 + 峰值保护 ----
//   老参数（3600 / 6× / 0.25× / 1%）只能覆盖 ±12 dB 的源差，
//   实测有的台差 15 dB 以上 ⇒ 小声的抬不起来、大声的压不下去，
//   用户听到的就是「有的特别大有的特别小」。
//   放宽到 10×（+20 dB）/ 0.16×（-16 dB）就够覆盖实测的差距了。
#define AGC_TARGET_RMS   4200       // 目标 RMS（16 位满刻度 32768，≈ -17.8 dBFS）
#define AGC_MAX_GAIN     10.0f      // 最轻的台最多放大 10 倍（+20 dB）
#define AGC_MIN_GAIN      0.16f     // 最响的台最多压到 1/6（-16 dB）
// 1.46.30：上升/下降分开。压下来要快（宁可闷一下也别炸），抬上去慢一点但别太慢：
//   从 1.0 倍爬到 6 倍，0.8%/块 ≈ 5 秒；再配上换台时"按这台学到的增益直接接上"，
//   用户听到的是"换过去就是这个音量"，不是"先小声一段再慢慢变大"。
//   步长是**乘性**的（每块 ×(1±step)），所以速率是恒定的 dB/秒，跟当前增益高低无关：
//   加法步长时从 1.0 爬到 9.5 倍要 24 秒（实测复刻 15.8 秒才进 ±1 dB），
//   用户听到的就是"换过去先小声一大段"。
#define AGC_STEP_UP       0.020f    // 每块 ×1.020（≈ +0.17 dB）→ ≈ +7.4 dB/秒
#define AGC_STEP_DN       0.050f    // 每块 ×0.950（≈ -0.45 dB）→ ≈ -19 dB/秒
#define AGC_UP_GATE_PK       900    // 只有峰值到这（≈ -31 dBFS）的块才允许加增益
#define AGC_FAST_GAIN       3.0f    // 换台后头一块直接接到 3 倍以内（再高怕撞上突然的大声）
#define AGC_PK_ENV_DECAY  0.994f    // 峰值包络每块衰减 0.6%（约 4 秒前的峰值不再算数）
#define AGC_GAIN_CACHE_N    320     // 每台学到的增益缓存条数（只放 RAM，掉电重学）
#define AGC_PEAK_CEIL  42000.0f     // 峰值保护：peak × 增益 不超过这个数（软限幅拐点在 26000）
// 1.46.30：有声书单独放宽这条线。
//   人声的峰均比 15~18 dB（音乐只有 10 dB），42000 相当于把增益钉死在 3.2~5 倍 ——
//   1.46.17 把目标提到 6400 也就白提了，所以用户到现在还是"书比台小很多"。
//   放到 90000 让增益够得着目标，冲上去的峰值交给软限幅去收（不必削顶：90000 进来也只压到 ~31.5k）。
#define AGC_PEAK_CEIL_BOOK 90000.0f

#define AGC_SILENT_PK       24      // 块峰值低于它算「静音块」（≈ -63 dBFS）
// ---- 1.46.17：有声书单独提响度 ----
//   有声书是人声 + 单声道 HE-AAC，源 RMS 只有 -29 dBFS 上下；
