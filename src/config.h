// ---------------- 电源保护 / 电流保护（1.21.0）----------------
// 这机器的用法是「一直插着 USB 当桌面收音机」，所以有两个真实的坏处要管：
//   ① 大音量 + 充电 + WiFi 同时跑 → 功放和充电 IC 一起发热，烫的是电池和屏幕；
//   ② 长期停在 4.2V 满电 → 锂电的日历老化（容量掉、鼓包），跟是否过充无关。
//
// 先说清楚固件**做不到**的：充电电流是充电 IC 外围电阻定死的，ESP32 改不了。
// 能改的只有「自己吃多少电」和「要不要让充电 IC 停一下」：
//
//   · 温度降载 —— 不依赖任何额外硬件，默认就开。
//     每 5 秒读一次芯片内部温度，按三档往下压「音量上限 / 亮度上限」；
//     最热那档直接暂停播放。大电流是发热主因，音量一压电流就下来。
//     （内部传感器绝对值 ±5℃，但**趋势**很准，所以阈值按"比平时高多少"设。）
//   · 满电降载 —— 满电判定成立时把亮度压一档，让系统总电流小于充电器供电能力，
//     避免在满电点「边充边放」来回充放电（来回充放比一直插着更伤电池）。
//     音量只压到 90，几乎无感 —— 压太狠用户会觉得"音量上不去"。
//   · 真停充 —— 要硬件。板子充电 IC 的 CE/EN 脚若接了 GPIO，填进 PIN_CHG_CTRL，
//     满电后固件真会关断充电、掉到 BATT_RECHG_MV 再开（笔记本的「保养模式」）。
//     默认 -1 = 没这条线，只做上面两层。
//   · 充电状态脚 —— 充电 IC 的 CHRG/STDBY 若接了 GPIO，填 PIN_CHG_STAT，
//     就能准确区分「正在充 / 已充满」，比拿电压猜准得多。默认 -1 = 猜。
