//   ① 充电时  终端 = 开路 + 充电电流×内阻。实测台阶 **580mV**
//      （1.46.55 日志：插着电 4234mV / 拔掉 3650mV）⇒ 充电期间电压不代表电量。
//   ② 放歌时  终端 = 开路 − 负载×内阻。实测掉 **274mV**（3945 → 3671）
//      ⇒ 查表之前必须先换成开路电压（关功放量 180ms）。
//   ③ **放电到 3.0V 以下会永久损伤锂电**（铜集流体溶解 / 析锂）。1.46.58 用 3400
//      关机是"还有电却关机"，但也不能反过来放到 3.0V。用户要求留 **10~15% 余量**，
