// ============================================================
//  album.h —— 「节目 / 专辑」这一层（1.7.0）
//
//  问题：有声书 75 集写进台表后，每集都是一个"台"。
//        旋钮一格一格转，转 15 下才出得了一部书；老人没法用。
//
//  做法：不新增字段、不改台表格式 —— 只认名字。
//        台名形如「三国演义 001」，就认为它属于专辑「三国演义」，
//        同专辑的台在组内连续，整段算一个「单元」。
//        旋钮换的是单元（＝一部书或一个普通台），不是集。
//
//  记忆：每部专辑播到第几集写在 /album.txt，
//        下次旋钮再转到这部书，从那一集接着放。
// ============================================================
#pragma once
#include <stdint.h>
#include <stddef.h>

// 读 /album.txt（开机时在 storeLoadCfg 之后调）
void albumBegin();

// 台名 → 专辑名。不是专辑成员返回 false。
//   "三国演义 001" → "三国演义"    true
//   "西安新闻广播"  →            false
// 判据：名字尾部「空格 + 2~4 位数字」，且前面至少 2 字节。
bool albumSplit(const char* stName, char* out, size_t n);

// i 所属单元（同一部书连续的那一段）在组内的首台；普通台返回 i 本身
int albumUnitStart(int i);

// 从 i 出发走 dir 个单元（>0 下一个 / <0 上一个），返回目标单元的首台。
// 只有一台时返回自己，不会越界。
int albumStep(int i, int dir);

// 单元入口：专辑用「上次听到的那一集」（没记录或已越界就回到首集），
// 普通台就是它自己。旋钮/切组落地后播的就是这个。
int albumEntry(int i);

// 记住第 i 台所在的专辑播到了这一集（每次真正开播时调）
void albumRemember(int i);

// 在 loop 里调：2 秒合并写一次盘
void albumTick();

// 调试用：当前记住的专辑条数
int albumCount();
