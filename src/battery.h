// ============================================================
//  battery.h —— 电量（1.19.0）
//
//  要解决的事：
//    这台机器是电池供电的，可原来固件完全不知道电量 —— 听着听着突然黑屏，
//    老人以为机器坏了。1.19.0 加三件事：
//      1. 每 30 秒量一次电池电压（分压 → ADC → 毫伏）；
//      2. 低于 5% 播「电量低，请充电」（10 分钟重复一次，不烦人）；
//      3. 真到底了播「没电了，关机」，念完再断掉整板电源（保护电池不过放）。
//
//  为什么判据用毫伏、还要一道 BATT_SEEN_HIGH_MV 的闸：
//    百分比是给人和 App 看的，真正做决定的必须是电压。而"引脚到底接没接分压"
//    没人说得准（见 config.h 的说明）—— 万一读到的是一根接在 3.3V 轨上的脚，
//    就会一直是 0%，机器会每十分钟喊一次没电、还会把自己关掉。
//    所以只有"本次上电读到过 3550mV 以上"之后，才允许播报和断电。
//
//  谁在用：
//    · ui.cpp    顶栏那个小电池图标（batteryOk() 为假就完全不画，界面跟旧版一样）
//    · net.cpp   /api/batt、/api/state 里的 batt 字段
//    · cloud.cpp 跨网时同样字段（外地也能看电量）
// ============================================================
#pragma once
#include <Arduino.h>

void batteryBegin();          // setup：storeBegin() 之后（要用 LittleFS 存校准值也没问题）
void batteryTick();           // loop：采样 / 平滑 / 三段判定

bool  batteryOk();            // 读到可信电池（引脚有效 + 读数合理 + 见过高位）
int   batteryPct();           // 0..100，-1 = 未知
int   batteryMv();            // 最近一次的平均电压（毫伏）
bool  batteryCharging();      // 电压在上行（粗判，用于不误关机）
bool  batteryLow();           // 当前处于「低电」态（< BATT_LOW_PCT）
int   batteryPin();           // 实际用的引脚（-1 = 没开）

// ---- 1.21.0：给「电源保护」用的两个判定 ----
//  batteryFull()  —— 已充满：电压到 4180mV 并稳住 2 分钟（有充电状态脚就直接读 STDBY）
//  batteryOnExt() —— 插着外接电源：电压持续 ≥4120mV 一分钟，或状态脚说在充
//  这两个都只是"推断"，插拔充电器会有几十秒延迟 —— 拿来做降载足够，
//  不要拿来当"充电器已断开"的硬判据。
bool  batteryFull();
bool  batteryOnExt();

void  batteryJson(String& o); // {"ok":1,"pct":82,"mv":3940,"chg":0,"low":0,"pin":4,...}

// ============================================================
//  1.38.2：电量校准（用户反馈「界面上的电量和真实不一样」）
//
//  为什么必须能校准：读数 = 引脚电压 × 分压比 × 校准系数。
//  分压比差 3% 就是 100mV = 十几% 电量。1.46.27 起用「充满时该是 4.2V」反算成 1.875
//  （原厂配置里的 1.71 偏低 9.6%，屏上永远是满电 53%）。
//  唯一可靠的办法是拿万用表量一下电池两端，把真实值填进来，机器自己缩放系数。
//
//  用法（App 里「电量校准」）：
//    量到电池实际 4.02V → batteryCalibrate(4020)
//    → 机器把 s_cal 乘上 (4020 / 当前读数)，存 /battcal.txt，立刻生效
// ============================================================
void  batteryCalibrate(int realMv);   // 用真实毫伏校准（返回 void，失败会打日志）
float batteryCalFactor();             // 当前校准系数
int   batteryRawMv();                 // 不补偿、不校准的原始读数（诊断用）
